CREATE TABLE public.investments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Kategorie" text,
  "Unternehmen" text NOT NULL,
  "Kurzbeschreibung" text,
  "Beschreibung" text,
  "Investiert_in" integer,
  "Fonds" text,
  "Website" text,
  "Website_URL" text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.investments TO anon;
GRANT SELECT ON public.investments TO authenticated;
GRANT ALL ON public.investments TO service_role;

ALTER TABLE public.investments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "investments readable by all" ON public.investments FOR SELECT USING (true);

CREATE TRIGGER investments_touch BEFORE UPDATE ON public.investments FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();